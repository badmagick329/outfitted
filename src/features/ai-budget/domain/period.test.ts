import { describe, expect, it } from "vitest";
import { aiBudgetPeriod } from "./period";

describe("London budget calendar", () => {
  it.each([
    ["2026-01-15T12:00:00Z", "2026-01", "2026-01-01T00:00:00Z", "2026-02-01T00:00:00Z"],
    ["2026-04-15T12:00:00Z", "2026-04", "2026-03-31T23:00:00Z", "2026-04-30T23:00:00Z"],
    ["2026-03-20T12:00:00Z", "2026-03", "2026-03-01T00:00:00Z", "2026-03-31T23:00:00Z"],
    ["2026-10-20T12:00:00Z", "2026-10", "2026-09-30T23:00:00Z", "2026-11-01T00:00:00Z"],
    ["2026-12-31T23:59:59.999Z", "2026-12", "2026-12-01T00:00:00Z", "2027-01-01T00:00:00Z"],
    ["2027-01-01T00:00:00Z", "2027-01", "2027-01-01T00:00:00Z", "2027-02-01T00:00:00Z"],
    ["2026-03-31T22:59:59.999Z", "2026-03", "2026-03-01T00:00:00Z", "2026-03-31T23:00:00Z"],
    ["2026-03-31T23:00:00Z", "2026-04", "2026-03-31T23:00:00Z", "2026-04-30T23:00:00Z"],
  ])("assigns %s to %s with UTC boundaries", (at, key, start, end) => {
    expect(aiBudgetPeriod(new Date(at))).toEqual({
      key,
      startsAt: new Date(start),
      endsAt: new Date(end),
    });
  });
});
